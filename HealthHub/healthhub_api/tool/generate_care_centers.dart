/// Compiles data/care_centers.jsonl into lib/care_centers_seed.dart, the
/// care centers the API seeds into its database (lib/db.dart). Run it from
/// healthhub_api/ after changing the data:
///
///   dart run tool/generate_care_centers.dart
///
/// It fails on a row that isn't valid (lib/care_centers.dart says what is)
/// and on two rows with the same key.
library;

import 'dart:convert';
import 'dart:io';

import 'package:healthhub_api/care_centers.dart';

const input = 'data/care_centers.jsonl';
const output = 'lib/care_centers_seed.dart';

void main() {
  final centers = readCareCenters(File(input).readAsLinesSync());
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_care_centers.dart from $input:')
    ..writeln('// edit the data and run the tool again, never this file.')
    ..writeln()
    ..writeln("import 'care_centers.dart';")
    ..writeln()
    ..writeln('/// The care centers seeded at start, ${centers.length} of them.')
    ..writeln('const careCenterSeed = <CareCenter>[');
  for (final c in centers) {
    out.writeln('  CareCenter(${c.values.map(_literal).join(', ')}),');
  }
  out.writeln('];');
  File(output).writeAsStringSync(out.toString());
  stdout.writeln('$output: ${centers.length} care centers');
}

/// The rows of [lines] (JSON Lines; blank lines skipped), checked.
List<CareCenter> readCareCenters(List<String> lines) {
  final centers = <CareCenter>[];
  final keys = <String>{};
  for (final (index, line) in lines.indexed) {
    if (line.trim().isEmpty) continue;
    final center = CareCenter.fromJson(
      (jsonDecode(line) as Map).cast<String, Object?>(),
    );
    if (!keys.add(center.key)) {
      throw FormatException('$input:${index + 1}: duplicate key ${center.key}');
    }
    centers.add(center);
  }
  return centers;
}

String _literal(Object? value) => switch (value) {
  null => 'null',
  final double d => d.toString(),
  // A raw-free Dart string: JSON's escaping, with $ escaped too.
  final String s => jsonEncode(s).replaceAll(r'$', r'\$'),
  _ => throw ArgumentError('unexpected value $value'),
};

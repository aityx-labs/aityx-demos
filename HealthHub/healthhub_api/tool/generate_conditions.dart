/// Compiles data/conditions/acute.json and chronic.json into
/// lib/conditions_seed.dart, the medical conditions the API seeds into its
/// database (lib/db.dart) and the simulation draws from. Run it from
/// healthhub_api/ after changing the data:
///
///   dart run tool/generate_conditions.dart
///
/// It fails, listing every problem, on an element that isn't valid
/// (lib/conditions.dart says what is) and on two conditions with the same
/// code. A missing file counts as no conditions of its type.
library;

import 'dart:convert';
import 'dart:io';

import 'package:healthhub_api/conditions.dart';

const inputDir = 'data/conditions';
const output = 'lib/conditions_seed.dart';

void main() {
  final List<MedicalCondition> conditions;
  try {
    conditions = readConditions(inputDir);
  } on FormatException catch (error) {
    stderr.writeln(error.message);
    exit(1);
  }
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_conditions.dart from $inputDir/*.json:')
    ..writeln('// edit the data and run the tool again, never this file.')
    ..writeln()
    ..writeln("import 'conditions.dart';")
    ..writeln()
    ..writeln('/// The medical conditions seeded at start, ${conditions.length} of them.')
    ..writeln('const conditionSeed = <MedicalCondition>[');
  for (final c in conditions) {
    out
      ..writeln('  MedicalCondition(')
      ..writeln('    code: ${_literal(c.code)},')
      ..writeln('    name: ${_literal(c.name)},')
      ..writeln('    type: ${_literal(c.type)},')
      ..writeln('    prevalence: ${_literal(c.prevalence)},')
      ..writeln('    minAge: ${c.minAge},')
      ..writeln('    maxAge: ${c.maxAge},')
      ..writeln('    summary: ${_literal(c.summary)},')
      ..writeln('    treatment: ${_literal(c.treatment)},')
      ..writeln('    treatmentDurationDays: ${c.treatmentDurationDays},')
      ..writeln('    duration: ${_literal(c.duration)},')
      ..writeln('    visitCount: ${c.visitCount},')
      ..writeln('    visitIntervalDays: ${c.visitIntervalDays},')
      ..writeln('    stayHours: ${c.stayHours},')
      ..writeln('    femaleShare: ${_literal(c.femaleShare)},')
      ..writeln('    urgent: ${c.urgent},')
      ..writeln('    followUpStayHours: ${c.followUpStayHours},')
      ..writeln('    courseGapDays: ${c.courseGapDays},');
    for (final kind in VisitKind.values) {
      out.writeln('    ${kind.json}: [');
      for (final template in c.templates(kind)) {
        out.writeln('      ${_literal(template)},');
      }
      out.writeln('    ],');
    }
    out.writeln('  ),');
  }
  out.writeln('];');
  File(output).writeAsStringSync(out.toString());
  stdout.writeln('$output: ${conditions.length} conditions');
}

/// The conditions of [dir]'s acute.json and chronic.json, in that order,
/// checked; throws a FormatException listing every problem found.
List<MedicalCondition> readConditions(String dir) {
  final conditions = <MedicalCondition>[];
  final problems = <String>[];
  final codes = <String>{};
  for (final type in ['acute', 'chronic']) {
    final file = File('$dir/$type.json');
    if (!file.existsSync()) continue;
    final Object? json;
    try {
      json = jsonDecode(file.readAsStringSync());
    } on FormatException catch (error) {
      problems.add('${file.path}: not JSON: ${error.message}');
      continue;
    }
    if (json is! List) {
      problems.add('${file.path}: not a JSON array');
      continue;
    }
    for (final (index, element) in json.indexed) {
      final where = '${file.path}[$index]';
      if (element is! Map) {
        problems.add('$where: not an object');
        continue;
      }
      final map = element.cast<String, Object?>();
      final found = MedicalCondition.problems(map, type: type);
      if (found.isNotEmpty) {
        problems.add('$where (${map['code']}): ${found.join('; ')}');
        continue;
      }
      final condition = MedicalCondition.fromJson(map, type: type);
      if (!codes.add(condition.code)) {
        problems.add('$where: duplicate code ${condition.code}');
        continue;
      }
      conditions.add(condition);
    }
  }
  if (problems.isNotEmpty) throw FormatException(problems.join('\n'));
  return conditions;
}

String _literal(Object? value) => switch (value) {
  null => 'null',
  final double d => d.toString(),
  // A raw-free Dart string: JSON's escaping, with $ escaped too.
  final String s => jsonEncode(s).replaceAll(r'$', r'\$'),
  _ => throw ArgumentError('unexpected value $value'),
};

/// Compiles data/triage/triage.json, the request HealthHub sends aityx to
/// triage a patient (Jev's questions and the decision; lib/triage.dart
/// adds the state), into lib/triage_seed.dart, since the API ships as a
/// single native executable. Run it from healthhub_api/ after changing
/// the model:
///
///   dart run tool/generate_triage.dart
///
/// It fails when the file isn't a JSON object with questions and a
/// decision.
library;

import 'dart:convert';
import 'dart:io';

const input = 'data/triage/triage.json';
const output = 'lib/triage_seed.dart';

void main() {
  final Object? json;
  try {
    json = jsonDecode(File(input).readAsStringSync());
  } on FormatException catch (error) {
    stderr.writeln('$input: not JSON: ${error.message}');
    exit(1);
  }
  if (json is! Map || json['questions'] is! Map || json['decision'] is! Map) {
    stderr.writeln('$input: not an object with "questions" and "decision"');
    exit(1);
  }
  // A Dart string of the JSON, compact: JSON's escaping, with $ escaped too.
  final literal = jsonEncode(jsonEncode(json)).replaceAll(r'$', r'\$');
  File(output).writeAsStringSync(
    '// GENERATED by tool/generate_triage.dart from $input:\n'
    '// edit the data and run the tool again, never this file.\n'
    '\n'
    '/// The triage request, but its state: Jev\'s questions and the decision.\n'
    'const triageModelJson = $literal;\n',
  );
  stdout.writeln('$output: ${(json['questions'] as Map).length} questions, '
      '${((json['decision'] as Map)['decisions'] as Map).length} decisions');
}

#!/usr/bin/env bash
# Serves the Flutter app on http://localhost:${FLUTTER_WEB_PORT}/app/. The
# app lives under /app/, leaving the site root free for other pages; the
# API is reached as /api/ on the same origin, so there's no CORS and it
# works behind a forwarded port (Codespaces) too. Two modes, WEB_MODE:
#   release  (the default, what `devbox services up` runs) the app's
#            release build (scripts/build.sh, only when the app changed),
#            served by healthhub_api/bin/web_server.dart compiled to a
#            native executable: one small process, as nginx under Docker
#            Compose. No hot reload.
#   debug    (`devbox run web`) Flutter's dev server, `flutter run` on the
#            web-server device, with hot reload (press r); it proxies
#            /api/ to the API itself. No Chrome is needed in either mode.
# Runs via `devbox services up` (see process-compose.yaml) or `devbox run web`.
set -euo pipefail

PORT="${FLUTTER_WEB_PORT:-9800}"
# 127.0.0.1, not localhost: Dart binds "localhost" to IPv6 [::1] only. The
# dev container sets HEALTHHUB_BIND_HOST=0.0.0.0, so its forwarded port
# reaches the server. Browsers still reach it at http://localhost:$PORT/app/.
HOST="${HEALTHHUB_BIND_HOST:-127.0.0.1}"
WEB_MODE="${WEB_MODE:-release}"
root="$(cd "$(dirname "$0")/.." && pwd)"

if [[ "$WEB_MODE" == release ]]; then
  bash "$root/scripts/build.sh" web web_server
  export WEB_ROOT="$root/healthhub_app/build/web"
  export FLUTTER_WEB_PORT="$PORT" HEALTHHUB_BIND_HOST="$HOST"
  export API_PORT="${API_PORT:-9801}"
  exec "$root/healthhub_api/build/web_server"
elif [[ "$WEB_MODE" != debug ]]; then
  echo "error: WEB_MODE must be release or debug (got '$WEB_MODE')" >&2
  exit 2
fi

cd "$root/healthhub_app"
source ../scripts/version.sh
# The dev server proxies /api/ to the local API (scripts/api.sh), so the app
# calls its own origin. The bare root goes to the API as well, which
# redirects it to /app/, so a forwarded port's URL opens the app as it is.
# The dev server has no redirect of its own. web_dev_config.yaml is
# generated here, git-ignored.
cat > web_dev_config.yaml <<YAML
# Generated by scripts/flutter-web.sh: the dev server's proxy to the API.
server:
  proxy:
    - prefix: "/api/"
      target: "http://127.0.0.1:${API_PORT:-9801}/"
    - regex: "^/\$"
      target: "http://127.0.0.1:${API_PORT:-9801}/"
YAML
flutter pub get
# The welcome screen shows X.Y.Z, Z being when this server started.
# API_BASE_URL: empty, so the app calls /api/ on its own origin (the
# proxy above).
exec flutter run -d web-server --web-hostname "$HOST" --web-port "$PORT" \
  --base-href /app/ \
  --dart-define="HEALTHHUB_VERSION=$VERSION" \
  --dart-define="API_BASE_URL=${API_BASE_URL:-}"

#!/usr/bin/env bash
# Serves the dashboard (datyx_dashboard/) on http://localhost:${FLUTTER_WEB_PORT}/app/.
# The app lives under /app/, leaving the site root free; the datyx API is
# reached as /api/ (and /q/) on the same origin, so there's no CORS and it
# works behind a forwarded port (Codespaces) too. Two modes, WEB_MODE:
#   release  (the default, what `devbox services up` runs) the app's
#            release build (scripts/build.sh, only when the app changed),
#            served by datyx_dashboard/bin/web_server.dart compiled to a
#            native executable: one small process, as nginx under Docker
#            Compose. No hot reload.
#   debug    (`devbox run web`) Flutter's dev server, `flutter run` on the
#            web-server device, with hot reload (press r); it proxies
#            /api/ and /q/ to the API itself. No Chrome is needed in either mode.
# The API is the datyx/ folder's, at DATYX_API_URL (scripts/env.sh).
# Runs via `devbox services up` (see process-compose.yaml) or `devbox run web`.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
# shellcheck source=env.sh
source "$root/scripts/env.sh"
# shellcheck source=version.sh
source "$root/scripts/version.sh"

PORT="$FLUTTER_WEB_PORT"
HOST="$DATYX_BIND_HOST"
API="$DATYX_API_URL"

if [[ "$WEB_MODE" == release ]]; then
  bash "$root/scripts/build.sh" web web_server
  export WEB_ROOT="$root/datyx_dashboard/build/web"
  export FLUTTER_WEB_PORT="$PORT" DATYX_BIND_HOST="$HOST" DATYX_API_URL="$API"
  exec "$root/datyx_dashboard/build/web_server"
elif [[ "$WEB_MODE" != debug ]]; then
  echo "error: WEB_MODE must be release or debug (got '$WEB_MODE')" >&2
  exit 2
fi

cd "$root/datyx_dashboard"
# The dev server proxies /api/ and /q/ (health, OpenAPI) to the API, so the
# app calls its own origin. web_dev_config.yaml is generated here,
# git-ignored.
cat > web_dev_config.yaml <<YAML
# Generated by scripts/flutter-web.sh: the dev server's proxy to the API.
server:
  proxy:
    - prefix: "/api/"
      target: "$API/"
    - prefix: "/q/"
      target: "$API/"
YAML
flutter pub get
# API_BASE_URL empty: the app calls /api/ on its own origin (the proxy).
exec flutter run -d web-server --web-hostname "$HOST" --web-port "$PORT" \
  --base-href /app/ \
  --dart-define="DATYX_VERSION=$VERSION" \
  --dart-define="API_BASE_URL=${API_BASE_URL:-}"

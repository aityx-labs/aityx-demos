#!/usr/bin/env bash
# Keeps what git ignores out of every Docker build context: appends to
# each .dockerignore (and each <name>.Dockerfile.dockerignore, which
# BuildKit reads instead of the folder's) the rules of the .gitignore
# files that apply to its context, so a .env, a log or a local build
# never ends up in an image. Run it after changing a .gitignore or adding
# a Dockerfile (one without an ignore file gets one); it rewrites only the
# block between its markers.
#
#   ./sync-dockerignore.sh          # update every ignore file
#   ./sync-dockerignore.sh --check  # exit 1 if any is out of date
#
# The rules that apply to a context are the repository's and its parent
# folders' .gitignore (their unanchored patterns) and every tracked
# .gitignore inside it, rewritten relative to the context. Negations
# (!.env.example, !.vscode/settings.json) are left out: the block only
# ever excludes more. .env and .env.* are always excluded.
set -euo pipefail

root="$(cd "$(dirname "$0")" && pwd)"
cd "$root"
begin="# BEGIN generated by sync-dockerignore.sh: what git ignores, never in an image"
end="# END generated by sync-dockerignore.sh"

# context <ignore file>: the build context it applies to, relative to the
# root: the parent of docker/ for <name>.Dockerfile.dockerignore (compose
# builds those with `context: .`), else its own folder.
context() {
  local dir
  dir="$(dirname "$1")"
  if [[ "$1" == *.Dockerfile.dockerignore && "$(basename "$dir")" == docker ]]; then
    dirname "$dir"
  else
    echo "$dir"
  fi
}

# rules <gitignore> <context>: the file's patterns as dockerignore rules
# relative to the context, one per line.
rules() {
  local file="$1" ctx="$2" dir prefix line pattern
  dir="$(dirname "$file")"
  [[ "$dir" == . ]] && dir=""
  # Where the .gitignore sits relative to the context: inside it (a
  # prefix), or at or above it (no prefix, unanchored patterns only).
  prefix=""
  if [[ -n "$dir" && "$dir" != "$ctx" && "$dir/" == "$ctx/"* ]]; then
    prefix="${dir#"$ctx/"}/"
  fi
  local inside=1
  [[ -z "$prefix" && "$dir" != "$ctx" ]] && inside=0
  while IFS= read -r line || [[ -n "$line" ]]; do
    line="${line%"${line##*[![:space:]]}"}"
    [[ -z "$line" || "$line" == \#* || "$line" == \!* ]] && continue
    pattern="${line%/}"
    if [[ "$pattern" == \*\*/* ]]; then
      echo "$prefix$pattern"
    elif [[ "$pattern" == /* || "$pattern" == */* ]]; then
      # Anchored to the .gitignore's folder: only from inside the context.
      [[ $inside == 1 ]] && echo "$prefix${pattern#/}"
    else
      echo "$prefix**/$pattern"
    fi
  done <"$file"
}

# block <context>: the generated block for a context.
block() {
  local ctx="$1" file
  echo "$begin"
  {
    echo "**/.env"
    echo "**/.env.*"
    # The root's and each parent folder's .gitignore, then those inside.
    file=".gitignore"
    [[ -f "$file" ]] && rules "$file" "$ctx"
    local path="" part
    IFS=/ read -ra parts <<<"$ctx"
    for part in "${parts[@]}"; do
      path="${path:+$path/}$part"
      [[ "$path" != "$ctx" && -f "$path/.gitignore" ]] && rules "$path/.gitignore" "$ctx"
    done
    git ls-files -- "$ctx/.gitignore" "$ctx/**/.gitignore" | sort | while IFS= read -r file; do
      rules "$file" "$ctx"
    done
  } | awk '!seen[$0]++'
  echo "$end"
}

# files <pattern>...: the files git tracks or would track (new ones too).
files() {
  git ls-files --cached --others --exclude-standard -- "$@" | sort -u
}

check=0
[[ "${1:-}" == --check ]] && check=1
stale=0

# Every Dockerfile needs an ignore file BuildKit reads: its own
# (<name>.Dockerfile.dockerignore) or its context's .dockerignore, the
# folder it's in, or the parent of docker/ for docker/<name>.Dockerfile.
# A missing one is created with the generated block alone.
while IFS= read -r dockerfile; do
  dir="$(dirname "$dockerfile")"
  [[ "$(basename "$dir")" == docker ]] && dir="$(dirname "$dir")"
  [[ -f "$dockerfile.dockerignore" || -f "$dir/.dockerignore" ]] && continue
  if [[ $check == 1 ]]; then
    echo "✗ $dockerfile has no ignore file (./sync-dockerignore.sh creates $dir/.dockerignore)" >&2
    stale=1
  else
    : >"$dir/.dockerignore"
  fi
done < <(files 'Dockerfile' '**/Dockerfile' '*.Dockerfile' '**/*.Dockerfile')

while IFS= read -r ignore; do
  ctx="$(context "$ignore")"
  # The file without its old block, then the new one.
  kept="$(awk -v b="$begin" -v e="$end" '$0==b{skip=1} !skip{print} $0==e{skip=0}' "$ignore")"
  kept="${kept%"${kept##*[!$'\n']}"}"
  new="${kept:+$kept$'\n\n'}$(block "$ctx")"
  if [[ "$new" != "$(cat "$ignore")" ]]; then
    if [[ $check == 1 ]]; then
      echo "✗ $ignore is out of date (./sync-dockerignore.sh)" >&2
      stale=1
    else
      printf '%s\n' "$new" >"$ignore"
      echo "· $ignore (context $ctx)"
    fi
  fi
done < <(files '.dockerignore' '**/.dockerignore' '*.dockerignore' '**/*.dockerignore')
exit $stale
